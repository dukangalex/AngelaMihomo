/// The Human Deep Space Exploration series （星辰大海之人类深空探索，
/// T181): twelve historic events as themes, sibling to the
/// twelve-constellation series under the 星辰大海 umbrella. Each
/// event carries the family's shared 21-token system (DESIGN doc
/// section 2) and paints its [DeepSpaceMotif] as the background
/// element layer — no constellation, no guardian.
class DeepSpaceThemeDef {
  final String id;

  /// The event's year, shown as the theme row's leading mark.
  final String year;
  final String nameZh;
  final String nameEn;
  final ZodiacSkeleton skeleton;
  final DeepSpaceMotif motif;
  final ZodiacVariant variant;

  const DeepSpaceThemeDef({
    required this.id,
    required this.year,
    required this.nameZh,
    required this.nameEn,
    required this.skeleton,
    required this.motif,
    required this.variant,
  });
}

