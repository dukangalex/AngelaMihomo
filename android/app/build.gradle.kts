// Required first-launch assets are generated by `dart run setup.dart assets`.
// Direct Flutter/Gradle builds must fail closed instead of shipping an unusable APK.
val verifyRuntimeAssets by tasks.registering {
    group = "verification"
    description = "Checks required first-launch data before Flutter asset packaging"
    val dataDirectory = rootProject.file("../assets/data")
    val required = listOf("zash.zip", "GeoSite.dat", "geoip.metadb", "ASN.mmdb", "BundleMRS.7z")
    inputs.files(required.map { dataDirectory.resolve(it) })
    doLast {
        required.forEach { name ->
            val asset = dataDirectory.resolve(name)
            if (!asset.isFile || asset.length() < 1024) {
                throw GradleException("Missing or empty runtime asset $name. Run dart run setup.dart assets before building.")
            }
            val prefix = asset.inputStream().use { input ->
                val bytes = ByteArray(64)
                val count = input.read(bytes)
                String(bytes, 0, maxOf(0, count), Charsets.US_ASCII).trimStart()
            }
            if (prefix.startsWith("<!DOCTYPE", ignoreCase = true) || prefix.startsWith("<html", ignoreCase = true)) {
                throw GradleException("Runtime asset $name contains an HTML response, not asset data.")
            }
        }
        ZipFile(dataDirectory.resolve("zash.zip")).use { archive ->
            val hasIndex = archive.entries().asSequence().any { !it.isDirectory && (it.name == "index.html" || it.name.endsWith("/index.html")) }
            if (!hasIndex) throw GradleException("zash.zip is missing index.html")
        }
        logger.lifecycle("Required runtime assets verified: " + required.joinToString())
    }
}

tasks.matching { it.name == "preBuild" || it.name.startsWith("compileFlutterBuild") }.configureEach {
    dependsOn(verifyRuntimeAssets)
}
