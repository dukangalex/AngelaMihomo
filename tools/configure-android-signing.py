#!/usr/bin/env python3
"""Owner-run helper. Never generates a key or prints credentials; explicit upload only."""
import argparse
import base64
import getpass
import os
from pathlib import Path
import subprocess

REPO = 'dukangalex/AngelaMihomo'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('keystore', type=Path)
    parser.add_argument('--alias', default='bettbox-release')
    args = parser.parse_args()
    data = args.keystore.expanduser().read_bytes()
    subprocess.run(['gh', 'auth', 'status'], check=True)
    password = getpass.getpass('Keystore password (hidden): ')
    # PKCS12 generated by the documented procedure uses the same key/store password.
    key_password = getpass.getpass('Key password (Enter = same as store, hidden): ') or password
    env = dict(os.environ, BETTBOX_STORE_PASSWORD=password)
    subprocess.run(['keytool', '-list', '-keystore', str(args.keystore.expanduser()),
                    '-alias', args.alias, '-storepass:env', 'BETTBOX_STORE_PASSWORD'],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    print('This uploads four repository Actions secrets to ' + REPO + '.')
    if input('Type UPLOAD to continue: ') != 'UPLOAD':
        print('Cancelled. No secrets changed.'); return
    values = {'KEYSTORE': base64.b64encode(data).decode('ascii'),
              'KEY_ALIAS': args.alias, 'STORE_PASSWORD': password, 'KEY_PASSWORD': key_password}
    for name, value in values.items():
        subprocess.run(['gh', 'secret', 'set', name, '--repo', REPO],
                       input=value.encode(), check=True, stdout=subprocess.DEVNULL)
        print(name + ': configured')
    print('Done. Keep your keystore and password backup; Actions secrets cannot recover them.')

if __name__ == '__main__':
    main()
